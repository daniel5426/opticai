import fs from "node:fs/promises";
import path from "node:path";
import ts from "typescript";

const sourceRoot = path.resolve("src");
const outputPath = path.join(sourceRoot, "localization/legacy-static-copy.ts");
const hebrew = /[\u0590-\u05ff]/;
const ignoredDirectories = new Set(["tests", "localization"]);

async function walk(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    if (entry.isDirectory()) {
      if (!ignoredDirectories.has(entry.name))
        files.push(...(await walk(path.join(directory, entry.name))));
    } else if (/\.(ts|tsx)$/.test(entry.name)) {
      files.push(path.join(directory, entry.name));
    }
  }
  return files;
}

function collectText(sourceFile) {
  const values = new Set();
  const visit = (node) => {
    if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) {
      const value = node.text.trim();
      if (
        value &&
        value.length < 420 &&
        hebrew.test(value) &&
        !/[{};]/.test(value)
      )
        values.add(value);
    }
    if (ts.isJsxText(node)) {
      const value = node.text.replace(/\s+/g, " ").trim();
      if (value && value.length < 420 && hebrew.test(value)) values.add(value);
    }
    ts.forEachChild(node, visit);
  };
  visit(sourceFile);
  return values;
}

async function translate(texts, target) {
  const translated = new Map();
  const chunks = [];
  let chunk = [];
  let length = 0;
  texts.forEach((text, index) => {
    const entry = `[[[${index}]]]${text}`;
    if (length + entry.length + 1 > 3500 && chunk.length) {
      chunks.push(chunk);
      chunk = [];
      length = 0;
    }
    chunk.push({ index, text, entry });
    length += entry.length + 1;
  });
  if (chunk.length) chunks.push(chunk);

  for (const entries of chunks) {
    const body = entries.map(({ entry }) => entry).join("\n");
    const url = new URL("https://translate.googleapis.com/translate_a/single");
    url.searchParams.set("client", "gtx");
    url.searchParams.set("sl", "he");
    url.searchParams.set("tl", target);
    url.searchParams.set("dt", "t");
    url.searchParams.set("q", body);
    const response = await fetch(url);
    if (!response.ok)
      throw new Error(`Translation request failed: ${response.status}`);
    const payload = await response.json();
    const value = payload?.[0]?.map((part) => part?.[0] ?? "").join("") ?? "";
    const segments = value.split(/\[\[\[(\d+)\]\]\]/g);
    for (let i = 1; i < segments.length; i += 2) {
      const index = Number(segments[i]);
      const text = segments[i + 1]?.trim();
      if (Number.isInteger(index) && text) translated.set(index, text);
    }
  }
  return texts.map((text, index) => translated.get(index) ?? text);
}

const files = await walk(sourceRoot);
const values = new Set();
for (const file of files) {
  const source = await fs.readFile(file, "utf8");
  const sourceFile = ts.createSourceFile(
    file,
    source,
    ts.ScriptTarget.Latest,
    true,
  );
  for (const value of collectText(sourceFile)) values.add(value);
}

const texts = [...values].sort((left, right) =>
  left.localeCompare(right, "he"),
);
if (process.argv.includes("--check")) {
  const current = await fs.readFile(outputPath, "utf8");
  const json = current.replace(/^.*?= /s, "").replace(/ as const;\s*$/, "");
  const catalog = JSON.parse(json);
  const missing = texts.filter((text) => !(text in catalog));
  if (missing.length) {
    console.error(`Missing ${missing.length} legacy UI translations.`);
    missing.forEach((text) => console.error(text));
    process.exitCode = 1;
  } else {
    console.log(`All ${texts.length} legacy UI strings are cataloged.`);
  }
  process.exit();
}
const [en, fr] = await Promise.all([
  translate(texts, "en"),
  translate(texts, "fr"),
]);
const catalog = Object.fromEntries(
  texts.map((text, index) => [text, { en: en[index], fr: fr[index] }]),
);
const output = `// Generated by scripts/generate-legacy-copy-catalog.mjs.\nexport const legacyStaticCopy = ${JSON.stringify(catalog, null, 2)} as const;\n`;
await fs.writeFile(outputPath, output);
console.log(`Generated ${texts.length} legacy UI translations.`);
