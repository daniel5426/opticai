import React from 'react';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen } from '@testing-library/react';
const state = vi.hoisted(() => ({path:'/inventory', open:true, clinic:1, closes:vi.fn(), host:null as HTMLDivElement|null}));
vi.mock('@tanstack/react-router', () => ({useLocation:() => ({pathname:state.path})}));
vi.mock('@/contexts/PrysmAgentContext', () => ({usePrysmAgent:() => ({available:true,chatOpen:state.open,closePatientChat:state.closes,scope:{clinicId:state.clinic},fullPageHost:state.host})}));
vi.mock('@/components/agent/AgentVoice', () => ({AgentVoiceCapture:() => null}));
vi.mock('@/components/ui/workspace-side-panel', () => ({WorkspaceSidePanel:({children,open}:any) => <aside hidden={!open}>{children}</aside>}));
vi.mock('@/components/agent/AgentChatPanel', () => ({AgentChatPanel:({compact}:any) => {const [draft,setDraft]=React.useState(''); return <div><span>{compact?'compact':'full'}</span><input aria-label="draft" value={draft} onChange={event=>setDraft(event.target.value)} /></div>;}}));
import { GlobalAgentPanel } from '@/components/agent/GlobalAgentPanel';
afterEach(cleanup);
it('moves the same conversation between sidebar and full page without losing a draft', () => {
  state.path='/inventory';state.open=true;
  const App=()=> <><div id="agent-full-host" /><GlobalAgentPanel /></>;
  const view=render(<App />);
  fireEvent.change(screen.getByLabelText('draft'),{target:{value:'Unsaved attachment message'}});
  const original=screen.getByLabelText('draft');
  state.host=document.getElementById('agent-full-host') as HTMLDivElement;
  state.path='/ai-assistant';view.rerender(<App />);
  expect(screen.getByText('full')).toBeVisible();
  expect(screen.getByLabelText('draft')).toBe(original);
  expect(original).toHaveValue('Unsaved attachment message');
  state.path='/clients/1';view.rerender(<App />);
  expect(screen.getByText('compact')).toBeVisible();
  expect(screen.getByLabelText('draft')).toBe(original);
});
it('attaches the preserved composer when the full-page host mounts after the route changes', () => {
  state.path='/inventory';state.host=null;
  const view=render(<GlobalAgentPanel />);
  fireEvent.change(screen.getByLabelText('draft'),{target:{value:'Keep this draft'}});
  const original=screen.getByLabelText('draft');
  state.path='/ai-assistant';view.rerender(<GlobalAgentPanel />);
  expect(screen.queryByLabelText('draft')).toBeNull();
  const host=document.createElement('div');document.body.appendChild(host);
  state.host=host;view.rerender(<GlobalAgentPanel />);
  expect(screen.getByLabelText('draft')).toBe(original);
  expect(original).toHaveValue('Keep this draft');
  view.unmount();host.remove();state.host=null;
});
